// Plotly appends "-15" to layout.map.layers symbol icon names before passing to MapLibre.
// We register our PNGs under those suffixed keys using the same Image() pattern Plotly uses
// for its own Maki icons.
window.addEventListener('load', function () {
    var ICONS = [
        { id: 'dredge-icon-15',   src: '/assets/dredge_marker.png' },
        { id: 'shoaling-icon-15', src: '/assets/shoaling_marker.png' },
        { id: 'gage-icon-15',     src: '/assets/raindrop.png' },
        { id: 'at-risk-icon-15', src: '/assets/at_risk_marker.png' },
        // same PNG, registered under a second key so this layer's icon-opacity
        // can be faded independently of the regular at-risk-icon layer -
        // used for the selected survey's marker while its depth polygons are showing
        { id: 'at-risk-icon-selected-15', src: '/assets/at_risk_marker.png' },
    ];
    var SELECTED_AT_RISK_OPACITY = 0.45;
    var iconListenerAdded = false;

    function addIcons(map) {
        ICONS.forEach(function (icon) {
            if (map.hasImage(icon.id)) return;
            var img = new Image();
            img.onload = function () {
                if (!map.hasImage(icon.id)) {
                    map.addImage(icon.id, img);
                    map.triggerRepaint();
                }
            };
            img.crossOrigin = 'Anonymous';
            img.src = icon.src;
        });
    }

    // MapLibre hides symbols that would visually collide with an already-placed
    // symbol unless overlap is explicitly allowed, which is why our icons were
    // popping in only once zoomed in far enough to separate them on screen.
    // Plotly's layers[].symbol schema has no field for this, so we patch the
    // generated style layers directly. Layer ids are regenerated by Plotly on
    // every redraw, so match on icon-image instead of a fixed id.
    function allowOverlap(map) {
        var style = map.getStyle();
        if (!style || !style.layers) return;
        style.layers.forEach(function (layer) {
            if (layer.type !== 'symbol' || !layer.layout) return;
            var iconImage = layer.layout['icon-image'];
            var isOurs = ICONS.some(function (icon) { return icon.id === iconImage; });
            if (!isOurs) return;
            try {
                map.setLayoutProperty(layer.id, 'icon-allow-overlap', true);
                map.setLayoutProperty(layer.id, 'icon-ignore-placement', true);
                if (iconImage === 'at-risk-icon-selected-15') {
                    map.setPaintProperty(layer.id, 'icon-opacity', SELECTED_AT_RISK_OPACITY);
                }
            } catch (e) { /* layer mid-transition; next afterplot pass will retry */ }
        });
    }

    function setup() {
        var gd = document.querySelector('#map .js-plotly-plot');
        if (!gd || !gd._fullLayout || !gd._fullLayout.map || !gd._fullLayout.map._subplot) {
            setTimeout(setup, 200);
            return;
        }
        var map = gd._fullLayout.map._subplot.map;
        if (!map) { setTimeout(setup, 200); return; }

        addIcons(map);
        allowOverlap(map);

        if (!iconListenerAdded) {
            iconListenerAdded = true;
            map.on('styleimagemissing', function (e) {
                var match = ICONS.find(function (icon) { return icon.id === e.id; });
                if (match) addIcons(map);
            });
        }

        if (gd.on) {
            gd.on('plotly_afterplot', function () {
                addIcons(map);
                allowOverlap(map);
            });
        }
    }

    setup();
});
